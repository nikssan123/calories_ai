/**
 * Bulgarian.
 *
 * Written in Bulgarian rather than translated from the English above it, which
 * is a different job and reads differently — the app's voice is short, warm and
 * slightly under-stated, and a gloss of "Nothing logged yet." lands as a form
 * validation error. Where the two languages want different sentences, this file
 * has the Bulgarian one.
 *
 * Two habits worth keeping for the next language:
 *
 * - **Second person singular, informal.** The English copy says "you" the way a
 *   friend does, and Bulgarian has to choose: "вие" would make the same
 *   sentences polite and distant. Every imperative here is «ти»-form.
 * - **No borrowed English where a Bulgarian word exists.** "Логвам" is what
 *   people say out loud and it is still the wrong register to print.
 *
 * Typed `Messages`, so a key added to `en.ts` and forgotten here fails
 * `pnpm -r typecheck` rather than rendering blank.
 */
