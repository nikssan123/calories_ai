/**
 * Czech.
 *
 * Informal "ty" throughout, never "vy" — the English says "you" the way a
 * friend does. Buttons and menu actions take the infinitive ("Uložit"), as Czech
 * software does; sentences addressed to the reader take the imperative.
 *
 * The Czech past tense and predicate adjectives are gendered ("zapsal jsi",
 * "jsi připraven"), and the reader could be anyone, so those sentences are
 * rephrased into the present, a neuter passive ("Zapsáno") or a noun — never
 * "zapsal(a)". An interpolated food, workout or coach name cannot be declined
 * from here, so it stays in the nominative: after a colon, or as the subject of
 * its sentence. A paid plan is a "tarif"; the coach, a person, is a "trenér".
 *
 * Plural categories: one (1), few (2–4), many (decimals, "1,5 dne"), other
 * (0, 5+). Quotes „…“; the English em dash becomes a spaced en dash. The native
 * twin carries the notes on individual choices.
 */
