/**
 * Romanian.
 *
 * Second person singular and informal throughout — „tu”, never
 * „dumneavoastră”. A calorie journal talks like a friend, and the polite form
 * would make the same sentences a form to fill in.
 *
 * Standard Romanian with comma-below ș and ț (U+0219/U+021B), never the cedilla
 * ş ţ, and „…” quotes. Three plural categories: one (1 zi), few (0, 2–19, 1,5
 * zile) and other, where numbers from 20 put "de" before the noun (20 de zile)
 * — so every `other` form starts with it, and the few entries that receive a
 * count as a string decide the "de" themselves.
 *
 * The reader is never gendered: no adjective or participle predicate about
 * "you" („ești pregătit”, „nou aici”) — a verb or a noun instead. The perfect
 * compus („ai notat”) does not agree, so it is used freely. The words match
 * the native app's: „a nota” for log, „ținta” for the daily goal, „antrenor”
 * for the human coach while the tier keeps its name, Coach.
 */
