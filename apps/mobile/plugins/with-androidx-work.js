const { withAppBuildGradle } = require('expo/config-plugins');

/**
 * Stops the two widget libraries from bringing in two copies of AndroidX Work.
 *
 * This app ships home-screen widgets on both platforms and uses a different
 * library for each: `react-native-android-widget` draws the Android ones,
 * `expo-widgets` the iOS ones. They are not interchangeable and both have to be
 * installed — but `expo-widgets` declares AndroidX Glance regardless of which
 * platform is being built, and that is where the collision comes from:
 *
 *     androidx.work:work-runtime:2.8.1       ← react-native-android-widget
 *     androidx.work:work-runtime-ktx:2.7.1   ← androidx.glance ← expo-widgets
 *
 * `work-runtime-ktx` was folded into `work-runtime` in 2.7.0, so the Kotlin
 * extensions now exist in both artifacts at these versions, and a release build
 * dies in `:app:checkReleaseDuplicateClasses` with a hundred lines about
 * `OneTimeWorkRequestKt`. Debug builds do not run that check, which is why the
 * emulator was happy the whole time and only a store build ever noticed.
 *
 * Aligning the two on 2.8.1 is enough: at that version the ktx artifact is a
 * shim over the same classes rather than a second copy of them. Pinning both
 * rather than excluding the ktx one keeps Glance's own dependency satisfied.
 *
 * A plugin rather than an edit to `android/app/build.gradle` because this is a
 * managed project: `android/` is regenerated by prebuild on every build and any
 * edit to it lasts until the next one.
 */

const MARKER = 'androidx.work:work-runtime';

const BLOCK = `
// Added by plugins/with-androidx-work.js — see the note there.
configurations.all {
    resolutionStrategy {
        force 'androidx.work:work-runtime:2.8.1'
        force 'androidx.work:work-runtime-ktx:2.8.1'
    }
}
`;

module.exports = function withAndroidxWork(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error(
        'with-androidx-work: app/build.gradle is not Groovy; the resolution strategy was not applied.',
      );
    }
    // Prebuild can run against an already-patched file, and two copies of a
    // `configurations.all` block is a Gradle error rather than a no-op.
    if (!cfg.modResults.contents.includes(MARKER)) {
      cfg.modResults.contents += BLOCK;
    }
    return cfg;
  });
};
